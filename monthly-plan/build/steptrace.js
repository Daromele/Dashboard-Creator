const probe=l=>p.evaluate(l=>({at:l,demo,storageProblem,tx:state.transactions.length,
  stored:(()=>{const r=localStorage.getItem(KEY);return r?JSON.parse(r).transactions.length:'NO KEY';})()}),l);
